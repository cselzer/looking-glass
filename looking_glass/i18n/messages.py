def _http_inventory() -> Dict[str, str]:
    from ..docs.catalog import HTTP_ROUTES

    out: Dict[str, str] = {}
    for route in HTTP_ROUTES:
        rid = route["id"]
        out[f"docs.http.{rid}.summary"] = str(route["summary"])
        out[f"docs.http.{rid}.notes"] = str(route["notes"])
        out[f"docs.http.{rid}.accept"] = str(route["accept"])
    return out


